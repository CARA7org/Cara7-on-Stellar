const DICTIONARIES: Record<Locale, Dictionary> = { en, fr };

interface LocaleContextValue {
  locale: Locale;
  dictionary: Dictionary;
  setLocale: (locale: Locale) => void;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

/**
 * Locale state for the report UI. Starts "en" so the client render matches
 * the server-rendered markup (React 19 hydration); the persisted choice in
 * localStorage("lang") is applied in an effect after mount. Fail-soft like
 * ThemeToggle: private mode just means the language does not persist.
 */
export function LocaleProvider({ children }: { children: ReactNode }): ReactNode {
  // NEVER read localStorage in the useState initializer - the first client
  // render must match SSR output or React 19 reports a hydration mismatch.
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const stored = localStorage.getItem("lang");
      if (stored === "en" || stored === "fr") {
        setLocaleState(stored);
        document.documentElement.lang = stored;
      }
    } catch {
      // private mode: language just won't persist
    }
  }, []);

  const setLocale = (next: Locale): void => {
    setLocaleState(next);
    document.documentElement.lang = next;
    try {
      localStorage.setItem("lang", next);
    } catch {
      // private mode: language just won't persist
    }
  };

  return (
    <LocaleContext.Provider
      value={{ locale, dictionary: DICTIONARIES[locale], setLocale }}
    >
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale(): LocaleContextValue {
  const context = useContext(LocaleContext);
  if (context === null) {
    throw new Error("useLocale must be used inside <LocaleProvider>");
  }
  return context;
}
